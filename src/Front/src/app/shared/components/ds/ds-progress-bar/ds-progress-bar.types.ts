/**
 * Mode for {@link DsProgressBarComponent}.
 * - `determinate`: value-driven bar (0-100).
 * - `indeterminate`: animated sliding bar (value ignored).
 */
export type DsProgressBarMode = 'determinate' | 'indeterminate';

/**
 * Color tone for {@link DsProgressBarComponent}.
 */
export type DsProgressBarTone = 'brand' | 'success' | 'danger';
